from public.words w
join public.deck_words dw on dw.word_id = w.id
join public.decks d on d.id = dw.deck_id
join public.collection_decks cd on cd.deck_id = d.id
join public.collections c on c.id = cd.collection_id
where c.name = '小学校の英語'
