from v
where w.english = v.english
  and w.japanese = v.japanese
  and coalesce(w.example_en, '') = ''
  and exists (
    select 1
    from public.deck_words dw
    join public.collection_decks cd on cd.deck_id = dw.deck_id
    join public.collections c on c.id = cd.collection_id
    where dw.word_id = w.id and c.name = '小学校の英語'
  );

